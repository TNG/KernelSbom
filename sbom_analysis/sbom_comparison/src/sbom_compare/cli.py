"""Command-line interface for sbom-compare.

Compares the SPDX SBOM documents in the `reference` and `candidate` folders of
a comparison directory and writes a self-contained HTML report (optionally a
JSON report) visualizing the semantic differences as a single git-style diff.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from sbom_compare import report as report_module
from sbom_compare.diff import unified_diff
from sbom_compare.load import (
    DOCUMENT_FILES,
    SbomCompareError,
    compare_document_set,
    load_document,
    normalize_document_set,
)


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="sbom-compare",
        description="Semantic comparison of SPDX SBOM documents generated by the kernel sbom tool",
    )
    parser.add_argument(
        "comparison",
        help="Directory containing a 'reference' and a 'candidate' folder, each holding the SBOM documents",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Path of the generated HTML report (default: <comparison>/sbom-compare-report.html)",
    )
    parser.add_argument(
        "--json",
        metavar="PATH",
        default=None,
        help="Also write a machine-readable JSON report to PATH",
    )
    return parser.parse_args(argv)


def _load_set(comparison: Path, variant: str) -> dict:
    variant_dir = comparison / variant
    if not variant_dir.is_dir():
        raise SbomCompareError(f"missing '{variant}' folder in comparison directory: {comparison}")
    return {name: load_document(variant_dir / name) for name in DOCUMENT_FILES}


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    comparison = Path(args.comparison)
    output_path = (
        Path(args.output) if args.output else comparison / "sbom-compare-report.html"
    )

    try:
        reference_docs = _load_set(comparison, "reference")
        candidate_docs = _load_set(comparison, "candidate")

        reference_normalized = normalize_document_set(reference_docs)
        candidate_normalized = normalize_document_set(candidate_docs)
        compared = compare_document_set(reference_normalized, candidate_normalized)

        report = {
            "comparison_dir": str(comparison),
            "documents": {
                name: {
                    **compared[name],
                    "diff": unified_diff(
                        compared[name]["reference_text"],
                        compared[name]["candidate_text"],
                        fromfile=f"reference/{name}",
                        tofile=f"candidate/{name}",
                    ),
                }
                for name in DOCUMENT_FILES
            },
        }
    except SbomCompareError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    report_module.write_report(output_path, report_module.render_html(report))
    if args.json:
        report_module.write_report(Path(args.json), report_module.render_json(report))

    for name in DOCUMENT_FILES:
        data = report["documents"][name]
        counts = ", ".join(
            f"{len(data[kind])} {kind}" for kind in ("added", "removed", "changed")
        )
        print(f"{name}: {counts}")
    print(f"Report written to {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())